-- L'export SQL crée les clés primaires en INTEGER sans séquence.
-- PostgreSQL n'attribue donc pas d'id automatiquement : ce script ajoute
-- une identité par défaut (non destructive) et recale la séquence sur les
-- données déjà importées.
--
-- À exécuter une seule fois, après l'import :
--   npm run db:identites

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'rendez_vous'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE rendez_vous ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'historique_statuts'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE historique_statuts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

SELECT setval(
  pg_get_serial_sequence('rendez_vous', 'id'),
  GREATEST(COALESCE((SELECT MAX(id) FROM rendez_vous), 0), 1),
  COALESCE((SELECT MAX(id) FROM rendez_vous), 0) > 0
);

SELECT setval(
  pg_get_serial_sequence('historique_statuts', 'id'),
  GREATEST(COALESCE((SELECT MAX(id) FROM historique_statuts), 0), 1),
  COALESCE((SELECT MAX(id) FROM historique_statuts), 0) > 0
);
